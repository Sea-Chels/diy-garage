export function repairsForPart(part: PartId, powertrain: Powertrain): Repair[] {
  return REPAIRS.filter((r) => r.parts.includes(part) && appliesTo(r, powertrain));
}

export function appliesTo(r: Repair, powertrain: Powertrain): boolean {
  return !r.powertrains || r.powertrains.includes(powertrain);
}

